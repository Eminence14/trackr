// Bundles each server entry into one self-contained file under api/, which Vercel runs as a function.
// One file per route avoids module-resolution surprises in Vercel's Node runtime.
import { build } from 'esbuild'

for (const name of ['parse', 'trending']) {
  await build({
    entryPoints: [`server/vercel/${name}.ts`],
    outfile: `api/${name}.js`,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    minify: true,
    legalComments: 'none',
    banner: { js: '// Generated by scripts/build-api.mjs. Edit server/ instead.' },
  })
}
console.log('api/ bundled')
